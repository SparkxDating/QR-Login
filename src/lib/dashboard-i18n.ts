export const dashboardMessages = { hi, en } as const;

export type DashboardMessageKey = keyof typeof hi;

export type Translate = (key: DashboardMessageKey, vars?: Record<string, string | number>) => string;

export function translate(
  lang: DashboardLang,
  key: DashboardMessageKey,
  vars?: Record<string, string | number>,
): string {
  let text: string = dashboardMessages[lang][key] ?? dashboardMessages.hi[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}


